/**
 * Writes supabase/seed.sql from the built-in sample data (content/*.ts), so the database starts
 * with what the fixtures hold. Treatments, city pages and guides keep published = false, because
 * row level security only shows published rows to the site. An editor sets published = true when a
 * page has real data and a reviewer.
 *   npm run seed:sql
 */
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { fixtures } from "../lib/data/fixtures";

const q = (v: unknown): string => {
  if (v === null || v === undefined) return "null";
  if (typeof v === "number") return String(v);
  if (typeof v === "boolean") return v ? "true" : "false";
  if (typeof v === "object") return `'${JSON.stringify(v).replace(/'/g, "''")}'::jsonb`;
  return `'${String(v).replace(/'/g, "''")}'`;
};

const rows = (table: string, cols: string[], data: unknown[][]): string =>
  data.length === 0 ? "" : `insert into public.${table} (${cols.join(", ")}) values\n${data.map((r) => `  (${r.map(q).join(", ")})`).join(",\n")}\non conflict do nothing;\n\n`;

const f = fixtures;
let sql = "-- Generated by `npm run seed:sql` from content/*.ts. Sample data only. Do not edit by hand.\n\n";

sql += rows("reviewers", ["id", "name", "credential", "reviewed_on", "is_sample", "photo_consent", "published"],
  f.reviewers.map((r) => [r.id, r.name, r.credential, r.reviewedOn, r.isSample, r.photoConsent, true]));
sql += rows("cities", ["slug", "name", "alt_name", "state", "areas", "summary", "nearby", "published"],
  f.cities.map((c) => [c.slug, c.name, c.altName ?? null, c.state, c.areas, c.summary, c.nearby, true]));
sql += rows("treatments", ["slug", "name", "menu_name", "alternate_name", "summary", "procedure", "national_range", "cost_factors", "desk_work", "card_blurb", "icon", "related", "read_slugs", "video_slugs", "reviewer_id", "content", "published"],
  f.treatments.map((t) => [t.slug, t.name, t.menuName, t.alternateName ?? null, t.summary, t.procedure, t.nationalRange ?? null, t.costFactors, t.deskWork, t.cardBlurb, t.icon, t.related, t.readSlugs, t.videoSlugs, t.reviewerId, t.content, t.published]));
sql += rows("treatment_city_pages",
  ["treatment_slug", "city_slug", "is_placeholder", "published", "reviewer_id", "meta_description", "price_min_inr", "price_max_inr", "price_from_inr", "price_valid_as_of", "price_collected_on", "price_data_points", "price_source_type", "price_is_sample", "price_chip_label", "price_basis", "includes", "facilities", "travel", "local_context", "usefulness", "signoffs", "lighthouse_ok", "before_after", "local_copy"],
  f.pages.map((p) => [p.treatmentSlug, p.citySlug, p.isPlaceholder, p.published, p.reviewerId, p.metaDescription ?? null, p.price?.minInr ?? null, p.price?.maxInr ?? null, p.price?.fromInr ?? null, p.price?.validAsOf ?? null, p.price?.collectedOn ?? null, p.price?.dataPoints ?? null, p.price?.sourceType ?? null, p.price?.isSample ?? true, p.price?.chipLabel ?? null, p.price?.basis ?? null, p.includes, p.facilities, p.travel, p.localContext, p.usefulness, p.signoffs, p.lighthouseOk, p.beforeAfter, p.localCopy]));
sql += rows("costs", ["treatment_slug", "city_slug", "position", "component", "min_inr", "max_inr", "note"],
  f.costs.map((c) => [c.treatmentSlug, c.citySlug, c.position, c.component, c.minInr, c.maxInr, c.note]));
sql += rows("faqs", ["id", "treatment_slug", "city_slug", "position", "question", "answer", "published"],
  f.faqs.map((x) => [x.id, x.treatmentSlug, x.citySlug, x.order, x.question, x.answer, true]));
sql += rows("blog_posts", ["slug", "title", "excerpt", "minutes", "thumb", "treatment_slug", "body", "reviewer_id", "published", "date_published", "date_modified"],
  f.posts.map((p) => [p.slug, p.title, p.excerpt, p.minutes, p.thumb, p.treatmentSlug, p.body, p.reviewerId, p.published, p.datePublished, p.dateModified]));
sql += rows("videos", ["slug", "title", "duration", "iso_duration", "description", "transcript", "poster", "poster_alt", "youtube_id", "upload_date", "is_sample", "published"],
  f.videos.map((v) => [v.slug, v.title, v.duration, v.isoDuration, v.description, v.transcript, v.poster, v.posterAlt, v.youtubeId, v.uploadDate, v.isSample, true]));

writeFileSync(join(process.cwd(), "supabase/seed.sql"), sql);
console.log(`supabase/seed.sql written (${sql.length} bytes)`);
